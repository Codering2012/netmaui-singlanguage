        /// <summary>
        /// Tests that OnModelCreating configures a unique index on the User.Email property.
        /// Validates that the Email property has exactly one index configured and that the index is marked as unique.
        /// </summary>
        [TestMethod]
        public void OnModelCreating_UserEmailIndex_ConfiguresUniqueIndex()
        {
            // Arrange
            DbContextOptions<AppDbContext> options = new DbContextOptionsBuilder<AppDbContext>()
                .UseInMemoryDatabase(databaseName: Guid.NewGuid().ToString())
                .Options;

            // Act
            using AppDbContext context = new AppDbContext(options);
            IEntityType userEntity = context.Model.FindEntityType(typeof(User))!;
            IIndex? emailIndex = userEntity.GetIndexes()
                .FirstOrDefault(i => i.Properties.Any(p => p.Name == nameof(User.Email)));

            // Assert
            Assert.IsNotNull(emailIndex, "Email index should be configured");
            Assert.IsTrue(emailIndex.IsUnique, "Email index should be unique");
        }

        /// <summary>
        /// Tests that OnModelCreating configures the User.Id property with ValueGeneratedNever strategy.
        /// Validates that the Id property will not have values auto-generated by the database.
        /// </summary>
        [TestMethod]
        public void OnModelCreating_UserIdProperty_ConfiguresValueGeneratedNever()
        {
            // Arrange
            DbContextOptions<AppDbContext> options = new DbContextOptionsBuilder<AppDbContext>()
                .UseInMemoryDatabase(databaseName: Guid.NewGuid().ToString())
                .Options;

            // Act
            using AppDbContext context = new AppDbContext(options);
            IEntityType userEntity = context.Model.FindEntityType(typeof(User))!;
