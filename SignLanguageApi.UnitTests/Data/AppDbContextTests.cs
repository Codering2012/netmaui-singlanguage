            // Assert
            Assert.IsNotNull(idProperty, "Id property should be found");
            Assert.AreEqual(Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.Never, idProperty.ValueGenerated, "Id should be configured as ValueGeneratedNever");
        }

